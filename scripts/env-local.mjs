#!/usr/bin/env node
/**
 * `npm run env:local`: writes the env files that point the app at the local Supabase
 * stack. It reads the values from `supabase status` and never prints them.
 *
 *   .env.localstack         read only by scripts/with-local-env.mjs (build:local,
 *                           check, test:e2e). Next never loads it by itself.
 *   .env.development.local  loaded by `next dev` ahead of .env.local, so `npm run dev`
 *                           uses the local stack while `next build` / `next start`
 *                           still read .env.local.
 *
 * Both files are gitignored (.env*). The keys are the ones in .env.example. Run it
 * again after `supabase start` if the stack's keys change.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { localStackStatus } from "./db/target.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

export const MUSICBRAINZ_UA_LOCAL = "earwrm-local/0.1.0 ( https://github.com/vishnumadhav108/earwrm )";

/** The value for every key in .env.example, taken from the local stack. */
export function localEnv(status) {
  return {
    NEXT_PUBLIC_SUPABASE_URL: status.API_URL,
    NEXT_PUBLIC_SUPABASE_ANON_KEY: status.ANON_KEY,
    MUSICBRAINZ_USER_AGENT: MUSICBRAINZ_UA_LOCAL,
    SUPABASE_SERVICE_ROLE_KEY: status.SERVICE_ROLE_KEY,
  };
}

/** Keys declared in .env.example (the contract every env must satisfy). */
export function exampleKeys() {
  return fs
    .readFileSync(path.join(root, ".env.example"), "utf8")
    .split(/\r?\n/)
    .map((l) => /^([A-Z][A-Z0-9_]*)=/.exec(l)?.[1])
    .filter(Boolean);
}

function main() {
  const { status, description } = localStackStatus();
  const env = localEnv(status);
  const missing = exampleKeys().filter((k) => !env[k]);
  if (missing.length) {
    console.error(`[env:local] no local value for: ${missing.join(", ")}. Update scripts/env-local.mjs.`);
    process.exit(1);
  }
  const body =
    "# Generated by `npm run env:local` from `supabase status`. Local stack only. Do not edit or commit.\n" +
    Object.entries(env)
      .map(([k, v]) => `${k}=${v}`)
      .join("\n") +
    "\n";
  for (const f of [".env.localstack", ".env.development.local"]) {
    fs.writeFileSync(path.join(root, f), body, { mode: 0o600 });
  }
  console.error(`[env:local] wrote .env.localstack and .env.development.local for the local stack (${description}).`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
